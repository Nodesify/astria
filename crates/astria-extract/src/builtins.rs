/// True if `name` is a builtin/global of `language` and should not produce a
/// call edge. Case-sensitive for capitalized type names, exact match only.
pub fn is_language_builtin(name: &str, language: &str) -> bool {
    builtin_set(language).contains(&name)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn filters_python_builtins() {
        assert!(is_language_builtin("print", "Python"));
        assert!(is_language_builtin("enumerate", "Python"));
        assert!(!is_language_builtin("my_func", "Python"));
        // case-sensitive: Print is not the builtin
        assert!(!is_language_builtin("Print", "Python"));
    }

    #[test]
    fn filters_js_globals() {
        assert!(is_language_builtin("Promise", "JavaScript"));
        assert!(is_language_builtin("console", "TypeScript"));
        assert!(!is_language_builtin("Promise", "Python"));
    }

    #[test]
    fn unknown_language_filters_nothing() {
        assert!(!is_language_builtin("print", "Zig"));
    }
}
