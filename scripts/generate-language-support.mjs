// Generate documentation from the same registry used by discovery and extraction.
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const languageSupportPath = 'website/docs/reference/language-support.md';
const read = (file) => readFileSync(path.join(root, file), 'utf8');

export function generateLanguageSupport() {
  const registry = read('crates/astria-core/src/languages.rs');
  const entries = [...registry.matchAll(/^\s+\w+, "([^"]+)", &\[([^\]]+)\], (\w+)::(\w+);$/gm)];
  if (!entries.length) throw new Error('No language registry entries found');
  const rows = entries.map(([, name, extensions, module, config]) => {
    const source = read(`crates/astria-extract/src/langs/${module}.rs`);
    const start = source.indexOf(`pub fn ${config}(`);
    if (start < 0) throw new Error(`Missing parser configuration: ${module}::${config}`);
    const rest = source.slice(start);
    const next = rest.indexOf('pub fn ', 1);
    const body = next < 0 ? rest : rest.slice(0, next);
    const kinds = (field) => {
      const match = body.match(new RegExp(`${field}: &\\[([^\\]]*)\\]`));
      if (!match) throw new Error(`Cannot read ${module}::${config}.${field}`);
      return [...match[1].matchAll(/"([^"]+)"/g)].map((m) => `\`${m[1]}\``).join(', ') || 'None';
    };
    const call = body.match(/call_type: "([^"]*)"/)?.[1];
    if (call === undefined) throw new Error(`Cannot read ${module}::${config}.call_type`);
    const exts = [...extensions.matchAll(/"([^"]+)"/g)].map((m) => `\`${m[1]}\``).join(', ');
    return `| ${name} | ${exts} | ${kinds('class_types')} | ${kinds('function_types')} | ${kinds('import_types')} | ${call ? `\`${call}\`` : 'None'} | ${kinds('closure_types')} |`;
  });
  return `---
sidebar_position: 4
title: Language support
description: Registered languages, discovered extensions, and configured tree-sitter syntax extraction.
keywords: [languages, tree-sitter, python, rust, typescript, go, java]
---

# Language support

<!-- Generated by scripts/generate-language-support.mjs. Do not edit by hand. -->

Astria registers **${entries.length} language configurations**. Discovery and parser selection share the registry in \`crates/astria-core/src/languages.rs\`.

The table lists configured tree-sitter node kinds, not a promise of complete language semantics or successful resolution of every construct. None means no node kind is configured for that category. Classes include language-specific containers such as HCL blocks; parser reuse and shared AST walker rules may limit extraction. Imports and calls are syntax candidates, not guarantees of resolved dependency edges. Closure kinds indicate configured anonymous-function extraction.

| Language | Discovered extensions | Class/container kinds | Function kinds | Import kinds | Call kind | Closure kinds |
| --- | --- | --- | --- | --- | --- | --- |
${rows.join('\n')}

## Adding a language

1. Add the grammar dependency and a parser config module in \`crates/astria-extract/src/langs/\`.
2. Export the module from \`langs/mod.rs\` and add one registration in \`crates/astria-core/src/languages.rs\`. Reference that registration for the config's name and extensions.
3. Map only AST kinds handled by the shared extraction walker.
4. Run \`node scripts/generate-language-support.mjs\` to regenerate this table. The docs-sync guard rejects stale generated content.
`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  writeFileSync(path.join(root, languageSupportPath), generateLanguageSupport());
  console.log(`Generated ${languageSupportPath}`);
}
