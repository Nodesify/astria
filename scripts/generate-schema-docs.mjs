// Generate the SQLite schema block in website/docs/explanation/architecture.md
// from the CREATE/ALTER statements in crates/astria-core/src/db.rs, so column
// listings cannot drift (same pattern as generate-language-support.mjs).
//
// Zero runtime dependencies. Run: node scripts/generate-schema-docs.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const schemaDocsPath = 'website/docs/explanation/architecture.md';
export const SCHEMA_BEGIN =
  '<!-- schema:begin - generated by scripts/generate-schema-docs.mjs; do not edit by hand -->';
export const SCHEMA_END = '<!-- schema:end -->';

// Presentation order (matches the docs' reading order); unknown tables append.
const TABLE_ORDER = [
  'nodes',
  'edges',
  'hyperedges',
  'communities',
  'file_manifest',
  'extraction_cache',
  'pipeline_runs',
  'query_history',
  'node_embeddings',
  'query_pairs',
  '_meta',
];

function productionSql() {
  const src = readFileSync(path.join(root, 'crates/astria-core/src/db.rs'), 'utf8');
  const i = src.indexOf('#[cfg(test)]');
  return i < 0 ? src : src.slice(0, i);
}

export function generateSchemaDocs() {
  const sql = productionSql();
  const columns = new Map();
  for (const m of sql.matchAll(/CREATE TABLE (?:IF NOT EXISTS )?(\w+) \(([^;]*?)\);/gs)) {
    const [, table, body] = m;
    const cols = [...body.matchAll(/(?:^|,)\s*([a-z_]+)\s+(?:TEXT|INTEGER|REAL|BLOB)\b/gi)].map(
      (c) => c[1],
    );
    if (!cols.length) throw new Error(`db.rs: no columns parsed for table ${table}`);
    columns.set(table, cols);
  }
  if (!columns.size) throw new Error('db.rs: no CREATE TABLE statements parsed');
  for (const m of sql.matchAll(/ALTER TABLE (\w+) ADD COLUMN ([a-z_]+)/g)) {
    const cols = columns.get(m[1]);
    if (!cols) throw new Error(`db.rs: ALTER TABLE for unknown table ${m[1]}`);
    if (!cols.includes(m[2])) cols.push(m[2]);
  }
  const ordered = [
    ...TABLE_ORDER.filter((t) => columns.has(t)),
    ...[...columns.keys()].filter((t) => !TABLE_ORDER.includes(t)).sort(),
  ];
  return ordered.map((t) => `- \`${t}\`: ${columns.get(t).map((c) => `\`${c}\``).join(', ')}`).join('\n');
}

export function renderSchemaPage(current) {
  if (!current.includes(SCHEMA_BEGIN) || !current.includes(SCHEMA_END)) {
    throw new Error(`${schemaDocsPath}: schema markers missing — add ${SCHEMA_BEGIN} and ${SCHEMA_END}`);
  }
  const pattern = new RegExp(`${SCHEMA_BEGIN}[\\s\\S]*?${SCHEMA_END}`);
  const block = `${SCHEMA_BEGIN}\n${generateSchemaDocs()}\n${SCHEMA_END}`.replace(/\$/g, '$$$$');
  return current.replace(pattern, block);
}

if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(fileURLToPath(import.meta.url))) {
  const file = path.join(root, schemaDocsPath);
  writeFileSync(file, renderSchemaPage(readFileSync(file, 'utf8')));
  console.log(`${schemaDocsPath}: schema block regenerated`);
}
